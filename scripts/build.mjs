import crypto from 'node:crypto';
import { promises as fs } from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

import { packCrx3, verifyCrx3 } from './crx.mjs';
import { getOrCreateChromiumKey } from './keys.mjs';
import { readZip, zipDirectory } from './zip.mjs';

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const SRC = path.join(ROOT, 'src');
const DIST = path.join(ROOT, 'dist');
const VERSION = JSON.parse(await fs.readFile(path.join(ROOT, 'package.json'), 'utf8')).version;
const DISPLAY_NAME = 'Force YouTube Resolution';
const ARTIFACT_BASE = 'force-youtube-resolution';

const ICON_SIZES = [16, 32, 48, 128];
const CONTENT_MATCHES = ['*://*.youtube.com/*'];

function baseManifest() {
    const icons = {};
    for (const size of ICON_SIZES) {
        icons[String(size)] = `icons/icon${size}.png`;
    }

    return {
        manifest_version: 3,
        name: DISPLAY_NAME,
        version: VERSION,
        description: 'Keeps YouTube at your chosen maximum resolution, with a live status indicator.',
        permissions: ['storage'],
        host_permissions: CONTENT_MATCHES,
        action: {
            default_title: DISPLAY_NAME,
            default_popup: 'popup.html',
            default_icon: icons
        },
        icons
    };
}

function chromiumManifest(publicKeyBase64) {
    return {
        ...baseManifest(),
        minimum_chrome_version: '111',
        key: publicKeyBase64,
        content_scripts: [
            {
                matches: CONTENT_MATCHES,
                js: ['core.js', 'content.js'],
                run_at: 'document_start',
                all_frames: false
            },
            {
                matches: CONTENT_MATCHES,
                js: ['page.bundle.js'],
                run_at: 'document_start',
                all_frames: false,
                world: 'MAIN'
            }
        ]
    };
}

function firefoxManifest() {
    return {
        ...baseManifest(),
        browser_specific_settings: {
            gecko: {
                id: 'force-youtube-resolution@local',
                strict_min_version: '128.0',
                data_collection_permissions: {
                    required: ['none']
                }
            }
        },
        content_scripts: [
            {
                matches: CONTENT_MATCHES,
                js: ['core.js', 'content.js'],
                run_at: 'document_start',
                all_frames: false
            },
            {
                matches: CONTENT_MATCHES,
                js: ['page.bundle.js'],
                run_at: 'document_start',
                all_frames: false,
                world: 'MAIN'
            }
        ]
    };
}

async function copyRuntimeFiles(destination) {
    await fs.mkdir(destination, { recursive: true });

    for (const file of ['core.js', 'content.js', 'popup.html', 'popup.css', 'popup.js']) {
        await fs.copyFile(path.join(SRC, file), path.join(destination, file));
    }

    await fs.mkdir(path.join(destination, 'icons'), { recursive: true });
    for (const size of ICON_SIZES) {
        await fs.copyFile(
            path.join(SRC, 'icons', `icon${size}.png`),
            path.join(destination, 'icons', `icon${size}.png`)
        );
    }

    const coreSource = await fs.readFile(path.join(SRC, 'core.js'), 'utf8');
    const pageSource = await fs.readFile(path.join(SRC, 'page.js'), 'utf8');
    const bundle = [
        '/* Generated by scripts/build.mjs from core.js + page.js. Do not edit. */',
        coreSource,
        pageSource
    ].join('\n\n');
    await fs.writeFile(path.join(destination, 'page.bundle.js'), bundle);
}

function validateManifest(manifest, browser) {
    if (manifest.manifest_version !== 3) throw new Error(`${browser}: manifest_version must be 3`);
    if (!/^\d+\.\d+\.\d+$/.test(manifest.version)) throw new Error(`${browser}: invalid version`);
    if (!Array.isArray(manifest.permissions) || manifest.permissions.length !== 1 ||
        manifest.permissions[0] !== 'storage') {
        throw new Error(`${browser}: unexpected permissions`);
    }
    if (!Array.isArray(manifest.host_permissions) ||
        manifest.host_permissions.some((pattern) => pattern !== '*://*.youtube.com/*')) {
        throw new Error(`${browser}: unexpected host permissions`);
    }
    if (!manifest.content_scripts || manifest.content_scripts.length !== 2) {
        throw new Error(`${browser}: expected exactly two content script entries`);
    }
    if (!manifest.content_scripts[1] || manifest.content_scripts[1].world !== 'MAIN') {
        throw new Error(`${browser}: main-world content script missing`);
    }
}

async function assertPackagedFiles(directory, manifest) {
    const required = ['manifest.json', 'core.js', 'content.js', 'page.bundle.js', 'popup.html', 'popup.css', 'popup.js'];
    for (const file of required) {
        await fs.access(path.join(directory, file));
    }
    for (const size of ICON_SIZES) {
        await fs.access(path.join(directory, 'icons', `icon${size}.png`));
    }
    const parsed = JSON.parse(await fs.readFile(path.join(directory, 'manifest.json'), 'utf8'));
    if (parsed.version !== manifest.version) throw new Error('Manifest version mismatch');
}

function formatBytes(bytes) {
    if (bytes < 1024) return `${bytes} B`;
    if (bytes < 1024 * 1024) return `${(bytes / 1024).toFixed(1)} KiB`;
    return `${(bytes / (1024 * 1024)).toFixed(2)} MiB`;
}

async function writeFileWithInfo(filePath, data) {
    await fs.writeFile(filePath, data);
    const stat = await fs.stat(filePath);
    console.log(`  ${path.relative(ROOT, filePath)}  (${formatBytes(stat.size)})`);
    return stat.size;
}

async function main() {
    console.log(`Building ${DISPLAY_NAME} v${VERSION}`);

    const key = await getOrCreateChromiumKey();
    if (key.created) {
        console.log(`  Generated a new Chromium signing key in .keys/ (keep it safe for updates).`);
    }

    await fs.rm(DIST, { recursive: true, force: true });
    const chromiumDir = path.join(DIST, 'chromium');
    const firefoxDir = path.join(DIST, 'firefox');

    await copyRuntimeFiles(chromiumDir);
    await copyRuntimeFiles(firefoxDir);

    const chromium = chromiumManifest(key.publicKeyBase64);
    const firefox = firefoxManifest();
    validateManifest(chromium, 'chromium');
    validateManifest(firefox, 'firefox');

    await fs.writeFile(path.join(chromiumDir, 'manifest.json'), JSON.stringify(chromium, null, 2) + '\n');
    await fs.writeFile(path.join(firefoxDir, 'manifest.json'), JSON.stringify(firefox, null, 2) + '\n');
    await assertPackagedFiles(chromiumDir, chromium);
    await assertPackagedFiles(firefoxDir, firefox);

    console.log('\nPackaging:');
    const xpiName = `${ARTIFACT_BASE}-firefox-${VERSION}.xpi`;
    const chromiumZipName = `${ARTIFACT_BASE}-chromium-${VERSION}.zip`;
    const crxName = `${ARTIFACT_BASE}-chromium-${VERSION}.crx`;

    const xpiBuffer = await zipDirectory(firefoxDir);
    await writeFileWithInfo(path.join(DIST, xpiName), xpiBuffer);

    const chromiumZip = await zipDirectory(chromiumDir);
    await writeFileWithInfo(path.join(DIST, chromiumZipName), chromiumZip);

    const crxBuffer = packCrx3(chromiumZip, key.privateKey, key.publicKeyDer, key.crxId);
    const verification = verifyCrx3(crxBuffer);
    if (!verification.valid) throw new Error(`CRX verification failed: ${verification.error}`);
    await writeFileWithInfo(path.join(DIST, crxName), crxBuffer);

    const xpiEntries = readZip(xpiBuffer);
    if (!xpiEntries.has('manifest.json') || !xpiEntries.has('page.bundle.js')) {
        throw new Error('XPI archive is missing required files');
    }

    const checksums = [
        `${crypto.createHash('sha256').update(xpiBuffer).digest('hex')}  ${xpiName}`,
        `${crypto.createHash('sha256').update(chromiumZip).digest('hex')}  ${chromiumZipName}`,
        `${crypto.createHash('sha256').update(crxBuffer).digest('hex')}  ${crxName}`,
        ''
    ].join('\n');
    await fs.writeFile(path.join(DIST, 'SHA256SUMS.txt'), checksums);

    console.log('\nDone.');
    console.log(`  Chromium extension ID: ${key.extensionId}`);
    console.log(`  Unpacked builds: dist/chromium, dist/firefox`);
    console.log(`  Firefox XPI is unsigned; see README.md for installation options.`);
}

main().catch((error) => {
    console.error(`Build failed: ${error.stack || error.message}`);
    process.exitCode = 1;
});
